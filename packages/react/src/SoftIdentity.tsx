export interface SoftTagProps extends React.HTMLAttributes<HTMLSpanElement> {
	/** `solid` is filled, `soft` is a tint, `outline` is a hairline. */
	variant?: "solid" | "soft" | "outline";
	tone?: IrisTone;
	/** Adds a remove affordance. Called when it is activated. */
	onRemove?: () => void;
	/** The label for that affordance. Defaults to a plain "移除". */
	removeLabel?: string;
	/** A small leading mark, usually an icon. */
	leading?: React.ReactNode;
}

/**
 * A label for something, that sits on the page rather than being part of it.
 *
 * The three variants are three amounts of the same substance rather than three
 * unrelated styles. `soft` is the default and is a wash — the tint is mixed with
 * the page rather than laid on it. `solid` is the same pigment at full strength,
 * which is why it needs a light text colour and is the only one that does.
 * `outline` is the pigment with no body at all, for a tag among many where three
 * filled pills in a row is a wall of colour.
 *
 * A tag with `onRemove` gets a real `<button>`, not a clickable span: it needs to
 * be reachable by Tab and by keyboard activation like any other control, and a
 * span with an `onClick` is neither.
 *
 * ```tsx
 * <SoftTag>水彩</SoftTag>
 * <SoftTag variant="solid" tone="blossom">主色</SoftTag>
 * <SoftTag onRemove={() => drop("paper")}>水彩纸</SoftTag>
 * ```
 */
export const SoftTag = forwardRef<HTMLSpanElement, SoftTagProps>(function SoftTag(
	{
		variant = "soft",
		tone = "iris",
		onRemove,
		removeLabel = "移除",
		leading,
		className,
		children,
		...props
	},
	ref,
) {
	return (
		<span
			{...props}
			ref={ref}
			className={className ? `ui-lib-soft-tag ${className}` : "ui-lib-soft-tag"}
			data-ui-lib-variant={variant}
			data-ui-lib-tone={tone}
		>
			{leading && (
				<span className="ui-lib-soft-tag__leading" aria-hidden="true">
					{leading}
				</span>
			)}
			<span className="ui-lib-soft-tag__label">{children}</span>
			{onRemove && (
				<button
					type="button"
					className="ui-lib-soft-tag__remove"
					aria-label={typeof children === "string" ? `${removeLabel} ${children}` : removeLabel}
					onClick={onRemove}
				>
					<svg viewBox="0 0 10 10" width="8" height="8" aria-hidden="true">
						<path
							d="M1.5 1.5 L8.5 8.5 M8.5 1.5 L1.5 8.5"
							stroke="currentColor"
							strokeWidth="1.6"
							strokeLinecap="round"
						/>
					</svg>
				</button>
			)}
		</span>
	);
});
